/**
 * Tanashvi Fintech B2B Mutual Fund Platform
 * Mutual Fund Financial Calculator Comprehensive Testbench
 * 
 * Verifies:
 * 1. Standard SIP compounding formula & yearly schedules
 * 2. Step-Up / Top-Up SIP compounding with annual step-up comparisons
 * 3. Reverse Target SIP engine (Annuity calculation)
 * 4. Become a Crorepati Goal Planner
 * 5. Children Higher Education & Marriage Planner (Education inflation adjusted)
 * 6. Comprehensive Two-Phase Retirement Engine (Accumulation & Distribution)
 * 7. Lumpsum & Compounding Wealth Engine
 * 8. SWP (Systematic Withdrawal Plan) Capital Depletion / Growth Simulator
 * 9. STP (Systematic Transfer Plan) Dual Fund Flow Simulator
 * 10. REST API HTTP Endpoints on Express Server
 */

import { createApp } from '../app.js';
import { Server } from 'http';
import { SipCalculator } from '../calculators/sipCalculators.js';
import { GoalCalculator } from '../calculators/goalCalculators.js';
import { WithdrawalCalculator } from '../calculators/withdrawalCalculators.js';

async function runCalculatorTestbench() {
  console.log('========================================================================');
  console.log('🧮 Tanashvi B2B Mutual Fund Platform: Financial Calculators Testbench');
  console.log('🛡️  Direct Alignment with AdvisorKhoj MFD Feature Suite');
  console.log('========================================================================\n');

  // --------------------------------------------------------------------------
  // 1. STANDARD SIP CALCULATOR
  // --------------------------------------------------------------------------
  console.log('📈 1. Testing Standard SIP Calculator...');
  const sipRes = SipCalculator.calculateSip({
    monthlyInvestment: 10000,
    expectedAnnualReturnRate: 12,
    tenureYears: 10
  });

  console.log(`   Monthly: ₹10,000 | 12% p.a. | 10 Years`);
  console.log(`   Total Invested: ₹${sipRes.totalInvestment.toLocaleString('en-IN')}`);
  console.log(`   Estimated Return: ₹${sipRes.estimatedReturns.toLocaleString('en-IN')}`);
  console.log(`   Maturity Value: ₹${sipRes.totalMaturityValue.toLocaleString('en-IN')}`);
  console.log(`   Wealth Multiplier: ${sipRes.wealthGainMultiplier}x`);
  console.log(`   Schedule Points: ${sipRes.schedule.length} years`);

  if (sipRes.totalInvestment !== 1200000) throw new Error('SIP Total Investment calculation incorrect');
  // At 12% p.a., 10,000/mo for 10 yrs matures to ~₹23.23 Lakhs
  if (sipRes.totalMaturityValue < 2300000 || sipRes.totalMaturityValue > 2350000) {
    throw new Error(`SIP Maturity value out of expected bounds: ${sipRes.totalMaturityValue}`);
  }
  console.log('   ✅ Standard SIP tests passed.\n');

  // --------------------------------------------------------------------------
  // 2. STEP-UP SIP CALCULATOR
  // --------------------------------------------------------------------------
  console.log('🚀 2. Testing Step-Up / Top-Up SIP Calculator...');
  const stepUpRes = SipCalculator.calculateStepUpSip({
    initialMonthlyInvestment: 10000,
    stepUpType: 'PERCENT',
    stepUpValue: 10, // 10% annual increase
    expectedAnnualReturnRate: 12,
    tenureYears: 10
  });

  console.log(`   Initial: ₹10,000 | 10% Annual Step-Up | 12% p.a. | 10 Years`);
  console.log(`   Total Invested: ₹${stepUpRes.totalInvestment.toLocaleString('en-IN')}`);
  console.log(`   Step-Up Maturity: ₹${stepUpRes.totalMaturityValue.toLocaleString('en-IN')}`);
  console.log(`   Normal SIP Maturity: ₹${stepUpRes.normalSipComparisonValue.toLocaleString('en-IN')}`);
  console.log(`   Extra Wealth Generated by Stepping Up: ₹${stepUpRes.stepUpExtraWealthGain.toLocaleString('en-IN')}`);

  if (stepUpRes.totalMaturityValue <= stepUpRes.normalSipComparisonValue) {
    throw new Error('Step-Up SIP must generate more wealth than flat SIP');
  }
  console.log('   ✅ Step-Up SIP tests passed.\n');

  // --------------------------------------------------------------------------
  // 3. TARGET AMOUNT SIP (REVERSE SIP)
  // --------------------------------------------------------------------------
  console.log('🎯 3. Testing Target SIP (Reverse SIP) Calculator...');
  const targetRes = SipCalculator.calculateTargetSip({
    targetCorpus: 10000000, // ₹1 Crore
    expectedAnnualReturnRate: 12,
    tenureYears: 15
  });

  console.log(`   Target Corpus: ₹1,00,00,000 (₹1 Cr) | 12% p.a. | 15 Years`);
  console.log(`   Required Monthly SIP: ₹${targetRes.requiredMonthlyInvestment.toLocaleString('en-IN')}`);
  console.log(`   Total Invested: ₹${targetRes.totalInvestment.toLocaleString('en-IN')}`);

  // At 12% over 15 years, ~₹20,000/mo generates ₹1 Crore
  if (targetRes.requiredMonthlyInvestment < 19000 || targetRes.requiredMonthlyInvestment > 21000) {
    throw new Error(`Target SIP monthly out of expected range: ${targetRes.requiredMonthlyInvestment}`);
  }
  console.log('   ✅ Target SIP tests passed.\n');

  // --------------------------------------------------------------------------
  // 4. BECOME A CROREPATI PLANNER
  // --------------------------------------------------------------------------
  console.log('💎 4. Testing Become A Crorepati Planner...');
  const crorepatiRes = GoalCalculator.calculateCrorepati({
    targetCrores: 1,
    expectedAnnualReturnRate: 13,
    tenureYears: 12
  });

  console.log(`   Target: ₹1 Crore | 13% p.a. | 12 Years`);
  console.log(`   Required Monthly SIP: ₹${crorepatiRes.requiredMonthlySip.toLocaleString('en-IN')}`);
  console.log(`   Wealth Created: ₹${crorepatiRes.wealthCreated.toLocaleString('en-IN')}`);
  if (crorepatiRes.requiredMonthlySip <= 0) throw new Error('Crorepati SIP must be positive');
  console.log('   ✅ Become A Crorepati Planner tests passed.\n');

  // --------------------------------------------------------------------------
  // 5. CHILD EDUCATION PLANNER
  // --------------------------------------------------------------------------
  console.log('🎓 5. Testing Child Education Planner...');
  const eduRes = GoalCalculator.calculateChildEducation({
    childCurrentAge: 3,
    collegeStartAge: 18, // 15 years away
    currentCostOfEducation: 2500000, // ₹25 Lakhs today
    educationInflationRate: 10,     // 10% education inflation
    expectedReturnRate: 12,
    existingSavings: 200000         // ₹2 Lakhs existing fund
  });

  console.log(`   Current Cost: ₹25,00,000 | Child Age: 3 -> 18 (15 yrs) | 10% Edu Inflation`);
  console.log(`   Future Cost at College Admission: ₹${eduRes.futureCostOfEducation.toLocaleString('en-IN')}`);
  console.log(`   Required Monthly SIP: ₹${eduRes.requiredMonthlySip.toLocaleString('en-IN')}`);
  console.log(`   Lumpsum Alternative Today: ₹${eduRes.lumpsumInvestmentTodayRequired.toLocaleString('en-IN')}`);

  if (eduRes.futureCostOfEducation < 10000000) { // ₹25L @ 10% for 15 yrs is > ₹1 Crore
    throw new Error(`Education future cost under-calculated: ${eduRes.futureCostOfEducation}`);
  }
  console.log('   ✅ Child Education Planner tests passed.\n');

  // --------------------------------------------------------------------------
  // 6. RETIREMENT PLANNING ENGINE
  // --------------------------------------------------------------------------
  console.log('🏖️  6. Testing Comprehensive Retirement Planning Engine...');
  const retRes = GoalCalculator.calculateRetirement({
    currentAge: 30,
    retirementAge: 60,
    lifeExpectancyYears: 85,
    currentMonthlyExpense: 50000,
    inflationRateAnnual: 6,
    preRetirementReturnRate: 12,
    postRetirementReturnRate: 8,
    existingRetirementSavings: 500000
  });

  console.log(`   Age: 30 -> 60 (30 yrs accumulation) | 60 -> 85 (25 yrs retirement)`);
  console.log(`   Current Monthly Expense: ₹50,000`);
  console.log(`   Monthly Expense at Retirement (6% inflation): ₹${retRes.monthlyExpenseAtRetirement.toLocaleString('en-IN')}`);
  console.log(`   Net Retirement Corpus Needed: ₹${retRes.netRetirementCorpusNeeded.toLocaleString('en-IN')}`);
  console.log(`   Monthly SIP Needed Today: ₹${retRes.requiredMonthlySip.toLocaleString('en-IN')}`);

  if (retRes.netRetirementCorpusNeeded <= 0 || retRes.requiredMonthlySip <= 0) {
    throw new Error('Retirement corpus and SIP must be positive');
  }
  console.log('   ✅ Retirement planning engine tests passed.\n');

  // --------------------------------------------------------------------------
  // 7. LUMPSUM CALCULATOR
  // --------------------------------------------------------------------------
  console.log('💰 7. Testing Lumpsum / Compounding Calculator...');
  const lumpsumRes = WithdrawalCalculator.calculateLumpsum({
    investmentAmount: 500000,
    expectedAnnualReturnRate: 12,
    tenureYears: 10
  });

  console.log(`   ₹5,00,000 Lumpsum @ 12% for 10 Years`);
  console.log(`   Total Maturity Value: ₹${lumpsumRes.totalMaturityValue.toLocaleString('en-IN')}`);
  console.log(`   Wealth Multiplier: ${lumpsumRes.wealthGainMultiplier}x`);
  // 500,000 * 1.12^10 = 1,552,924
  if (lumpsumRes.totalMaturityValue < 1540000 || lumpsumRes.totalMaturityValue > 1560000) {
    throw new Error(`Lumpsum maturity out of bounds: ${lumpsumRes.totalMaturityValue}`);
  }
  console.log('   ✅ Lumpsum calculator tests passed.\n');

  // --------------------------------------------------------------------------
  // 8. SWP (SYSTEMATIC WITHDRAWAL PLAN)
  // --------------------------------------------------------------------------
  console.log('🏦 8. Testing SWP (Systematic Withdrawal Plan)...');
  const swpRes = WithdrawalCalculator.calculateSwp({
    initialInvestment: 5000000, // ₹50 Lakhs
    monthlyWithdrawal: 35000,   // ₹35,000 / month
    expectedAnnualReturnRate: 9, // 9% return
    tenureYears: 10
  });

  console.log(`   Initial Corpus: ₹50,00,000 | Withdrawing ₹35,000/mo @ 9% for 10 Years`);
  console.log(`   Total Withdrawn: ₹${swpRes.totalAmountWithdrawn.toLocaleString('en-IN')}`);
  console.log(`   Remaining Balance: ₹${swpRes.finalBalanceRemaining.toLocaleString('en-IN')}`);
  console.log(`   Total Wealth Generated: ₹${swpRes.totalProfitGenerated.toLocaleString('en-IN')}`);
  console.log(`   Corpus Exhausted Early: ${swpRes.isCorpusExhaustedEarly}`);

  if (swpRes.totalAmountWithdrawn !== 4200000) throw new Error('SWP total withdrawn mismatch');
  if (swpRes.isCorpusExhaustedEarly) throw new Error('Corpus should not be exhausted with safe withdrawal rate');
  console.log('   ✅ SWP calculator tests passed.\n');

  // --------------------------------------------------------------------------
  // 9. STP (SYSTEMATIC TRANSFER PLAN)
  // --------------------------------------------------------------------------
  console.log('🔄 9. Testing STP (Systematic Transfer Plan)...');
  const stpRes = WithdrawalCalculator.calculateStp({
    sourceInvestmentAmount: 1000000, // ₹10 Lakhs in Liquid Fund
    monthlyTransferAmount: 50000,    // Transfer ₹50,000/mo to Equity Fund
    sourceSchemeReturnRate: 6,       // 6% Liquid return
    targetSchemeReturnRate: 12,      // 12% Equity return
    tenureMonths: 20
  });

  console.log(`   Source: ₹10,00,000 (Liquid 6%) -> Transferring ₹50,000/mo to Target (Equity 12%) for 20 Months`);
  console.log(`   Total Transferred: ₹${stpRes.totalTransferred.toLocaleString('en-IN')}`);
  console.log(`   Remaining in Liquid: ₹${stpRes.remainingSourceBalance.toLocaleString('en-IN')}`);
  console.log(`   Accumulated in Equity: ₹${stpRes.targetMaturityValue.toLocaleString('en-IN')}`);
  console.log(`   Net Combined Portfolio Value: ₹${stpRes.totalCombinedValue.toLocaleString('en-IN')}`);

  if (stpRes.totalCombinedValue <= 1000000) throw new Error('Combined portfolio value must show capital appreciation');
  console.log('   ✅ STP calculator tests passed.\n');

  // --------------------------------------------------------------------------
  // 10. REST API HTTP ENDPOINTS TESTBENCH
  // --------------------------------------------------------------------------
  console.log('🌐 10. Testing Calculator REST API Gateway Endpoints...');
  const app = createApp();
  let server: Server;
  let baseUrl = '';

  await new Promise<void>((resolve) => {
    server = app.listen(0, () => {
      const address = server.address() as any;
      baseUrl = `http://localhost:${address.port}`;
      resolve();
    });
  });

  try {
    // A: Test POST /api/v1/calculators/sip
    const apiSip = await fetch(`${baseUrl}/api/v1/calculators/sip`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ monthlyInvestment: 5000, expectedAnnualReturnRate: 12, tenureYears: 5 })
    });
    const sipJson = await apiSip.json();
    if (apiSip.status !== 200 || !sipJson.success) throw new Error('API SIP endpoint failed');
    console.log(`   POST /api/v1/calculators/sip: Status 200 OK (Maturity: ₹${sipJson.data.totalMaturityValue})`);

    // B: Test POST /api/v1/calculators/step-up-sip
    const apiStepUp = await fetch(`${baseUrl}/api/v1/calculators/step-up-sip`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ initialMonthlyInvestment: 5000, stepUpType: 'PERCENT', stepUpValue: 10, expectedAnnualReturnRate: 12, tenureYears: 5 })
    });
    const stepUpJson = await apiStepUp.json();
    if (apiStepUp.status !== 200 || !stepUpJson.success) throw new Error('API Step-up SIP endpoint failed');
    console.log(`   POST /api/v1/calculators/step-up-sip: Status 200 OK (Extra gain: ₹${stepUpJson.data.stepUpExtraWealthGain})`);

    // C: Test POST /api/v1/calculators/crorepati
    const apiCrorepati = await fetch(`${baseUrl}/api/v1/calculators/crorepati`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ targetCrores: 1, expectedAnnualReturnRate: 12, tenureYears: 15 })
    });
    const crorepatiJson = await apiCrorepati.json();
    if (apiCrorepati.status !== 200 || !crorepatiJson.success) throw new Error('API Crorepati endpoint failed');
    console.log(`   POST /api/v1/calculators/crorepati: Status 200 OK (Monthly SIP needed: ₹${crorepatiJson.data.requiredMonthlySip})`);

    // D: Test Validation Error Handling
    const apiBad = await fetch(`${baseUrl}/api/v1/calculators/sip`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ monthlyInvestment: 0 })
    });
    if (apiBad.status !== 400) throw new Error('Expected 400 on missing parameters');
    console.log(`   Validation check on missing params: Correctly returned 400 Bad Request`);

    console.log('   ✅ All REST API calculator endpoints verified successfully.');
  } finally {
    server!.close();
  }

  console.log('\n========================================================================');
  console.log('🎉 ALL MUTUAL FUND FINANCIAL CALCULATOR TESTS PASSED (100% SUCCESS)');
  console.log('========================================================================');
}

runCalculatorTestbench().catch((err) => {
  console.error('❌ Calculator testbench failed:', err);
  process.exit(1);
});

