/**
 * BSE StAR MF v2.0 - Order Engine & Mandate Type Definitions
 * 
 * Complies with BSE StAR MF v2 /order_new, /sxp_register, and /mandate_register:
 * - Internal Platform ID <-> BSE Order/Reg/Mandate ID mapping
 * - Lumpsum Purchases, Redemptions, Switches
 * - Systematic SxP Engine (SIP, XSIP, STP, SWP)
 * - eNACH / UPI AutoPay Mandate tracking
 * - SEBI / AMFI EUIN & ARN attribution
 */

export type OrderType = 'PURCHASE' | 'REDEMPTION' | 'SWITCH';
export type PurchaseType = 'FRESH' | 'ADDITIONAL';
export type PaymentMode = 'UPI' | 'NETBANKING' | 'NEFT_RTGS' | 'MANDATE';
export type PhysOrDemat = 'P' | 'D';

export type OrderStatus =
  | 'DRAFT'
  | 'VALIDATED'
  | 'QUEUED_FOR_BSE'
  | 'SUBMITTED_TO_BSE'
  | 'ACCEPTED_BY_BSE'
  | 'REJECTED_BY_BSE'
  | 'AWAITING_PAYMENT'
  | 'PAYMENT_CONFIRMED'
  | 'PROCESSED_BY_RTA'
  | 'UNITS_ALLOTTED'
  | 'CANCELLED'
  | 'EXPIRED';

export interface OrderRegulatoryAttribution {
  subBrArn: string;     // Distributor MFD ARN
  subBrCode?: string;   // Branch Code
  euin?: string;        // RM EUIN
  euinFlag: boolean;    // True if EUIN provided, False if execution-only
  partnerId?: string;
}

export interface MutualFundOrder {
  id?: string;
  tenantId: string;
  uccId: string;
  uccClientCode: string;

  // Key Mapping: Platform Internal Ref <-> BSE Exchange Order Number
  memOrdRefId: string; // Unique Internal Order Reference (e.g. 'ORD-20261031-0001')
  bseOrderNo?: string; // Generated by BSE StAR MF v2 upon submission
  bseInternalRefNo?: string;

  orderType: OrderType;
  purchaseType?: PurchaseType;
  orderSource: 'LUMPSUM' | 'SIP_INSTALLMENT' | 'STP_LEG' | 'SWP_LEG';

  schemeBseCode: string;
  destSchemeBseCode?: string; // For switch
  folioNumber?: string;
  destFolioNumber?: string;
  physOrDemat: PhysOrDemat;

  amount: number;
  units?: number;
  isUnits: boolean;
  allUnits: boolean;
  currency: 'INR';

  regulatory: OrderRegulatoryAttribution;

  // Payment Tracking
  paymentMode: PaymentMode;
  mandateId?: string; // Required when paymentMode is 'MANDATE'
  paymentStatus: 'PENDING' | 'LINK_GENERATED' | 'SUCCESS' | 'FAILED' | 'REVERSED' | 'EXPIRED';
  bsePaymentLink?: string;
  paymentRefId?: string;

  // State Machine Lifecycle
  status: OrderStatus;
  rejectionCode?: string;
  rejectionReason?: string;

  // Cut-off and NAV
  orderTimestamp: string;
  cutoffTime: string;
  isSameDayNav: boolean;
  allottedNav?: number;
  allottedUnits?: number;
  allotmentDate?: string;

  traceId: string;
}

export type SxpType = 'SIP' | 'XSIP' | 'STP' | 'SWP';
export type SxpFrequency = 'd' | 'w' | 'm' | 'q'; // Daily, Weekly, Monthly, Quarterly

export interface SystematicRegistration {
  id?: string;
  tenantId: string;
  uccId: string;
  uccClientCode: string;

  // Key Mapping: Platform Internal Ref <-> BSE Registration Number
  memSxpRefId: string; // Unique Internal SIP Reference (e.g. 'SIP-20261031-0001')
  bseRegNo?: string;   // BSE Registration Number returned upon registration

  sxpType: SxpType;
  srcSchemeBseCode: string;
  destSchemeBseCode?: string; // For STP
  srcFolio?: string;
  destFolio?: string;
  physOrDemat: PhysOrDemat;

  frequency: SxpFrequency;
  installmentAmount: number;
  units?: number;
  isUnits: boolean;
  installmentDay: number; // Day of month (1 - 31)
  startDate: string;      // YYYY-MM-DD
  endDate?: string;       // YYYY-MM-DD
  isPerpetual: boolean;
  totalInstallments?: number;
  firstOrderToday: boolean;

  mandateId?: string;

  // Top-Up / Step-Up
  hasTopup: boolean;
  topupType?: 'PERCENT' | 'AMOUNT';
  topupValue?: number;
  topupFrequency?: 'HALF_YEARLY' | 'YEARLY';

  regulatory: OrderRegulatoryAttribution;

  status: 'INITIATED' | 'SUBMITTED_TO_BSE' | 'ACTIVE' | 'PAUSED' | 'RESUMED' | 'CANCELLED' | 'COMPLETED' | 'REJECTED';
  pauseStartDate?: string;
  pauseEndDate?: string;
  cancellationDate?: string;
  rejectionReason?: string;
}

export interface MandateRegistration {
  id?: string;
  tenantId: string;
  uccId: string;
  uccClientCode: string;
  bankAccountId: string;

  // Key Mapping: Platform Internal Ref <-> BSE Mandate ID & NPCI UMRN
  memMandateId: string; // Internal Ref (e.g. 'MM-20261031-0001')
  bseMandateId?: string; // BSE Mandate ID
  umrn?: string;         // Unique Mandate Reference Number (UMRN)

  mandateType: 'ENACH' | 'UPI_AUTOPAY' | 'NACH_PAPER';
  maxAmount: number;
  startDate: string;
  validTill: string;
  frequency: string;

  authMode: 'NETBANKING' | 'DEBIT_CARD' | 'UPI' | 'PHYSICAL_SIGN';
  authUrl?: string;

  status: 'INITIATED' | 'PENDING_INVESTOR_AUTH' | 'SUBMITTED_TO_BANK' | 'ACTIVE_APPROVED' | 'REJECTED' | 'CANCELLED' | 'EXPIRED';
  rejectionReason?: string;

  regulatory: OrderRegulatoryAttribution;
}

