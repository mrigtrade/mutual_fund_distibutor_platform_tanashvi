-- 3.1 Mandate Master (eNACH, UPI AutoPay, Paper NACH for SIP execution)
CREATE TABLE IF NOT EXISTS tanashvi_core.mandates (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    tenant_id UUID NOT NULL REFERENCES tanashvi_core.tenants(id) ON DELETE CASCADE,
    ucc_id UUID NOT NULL REFERENCES tanashvi_core.ucc_investors(id) ON DELETE CASCADE,
    bank_account_id UUID NOT NULL REFERENCES tanashvi_core.ucc_bank_accounts(id),
    
    -- Mandate Identifiers (Platform internal mapped to BSE)
    mem_mandate_id VARCHAR(32) NOT NULL,      -- Internal Ref (e.g. 'MM-20261031-0001')
    bse_mandate_id VARCHAR(32),               -- BSE StAR Mandate ID returned by API
    umrn VARCHAR(32),                         -- NPCI Unique Mandate Reference Number
    
    -- Mandate Parameters
    mandate_type VARCHAR(20) NOT NULL CHECK (mandate_type IN ('ENACH', 'UPI_AUTOPAY', 'NACH_PAPER')),
    max_amount NUMERIC(14, 2) NOT NULL,       -- Max debit limit per transaction (e.g. 100000.00)
    start_date DATE NOT NULL,
    valid_till DATE NOT NULL,
    frequency VARCHAR(30) NOT NULL DEFAULT 'AS AND WHEN PRESENTED',
    
    -- Authorization & Links
    auth_mode VARCHAR(20) NOT NULL DEFAULT 'NETBANKING' CHECK (auth_mode IN ('NETBANKING', 'DEBIT_CARD', 'UPI', 'PHYSICAL_SIGN')),
    auth_url TEXT,                            -- BSE Auth link sent to investor
    
    -- Status Lifecycle
    status VARCHAR(25) NOT NULL DEFAULT 'INITIATED' CHECK (status IN (
        'INITIATED', 'PENDING_INVESTOR_AUTH', 'SUBMITTED_TO_BANK', 'ACTIVE_APPROVED', 'REJECTED', 'CANCELLED', 'EXPIRED'
    )),
    rejection_reason TEXT,
    
    -- Regulatory routing
    sub_br_arn VARCHAR(32),
    sub_br_code VARCHAR(32),
    euin VARCHAR(16),
    
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    
    CONSTRAINT uq_tenant_mem_mandate_id UNIQUE (tenant_id, mem_mandate_id)
);

CREATE INDEX idx_mandates_tenant ON tanashvi_core.mandates(tenant_id);
CREATE INDEX idx_mandates_ucc ON tanashvi_core.mandates(ucc_id);
CREATE INDEX idx_mandates_bse_id ON tanashvi_core.mandates(bse_mandate_id);
CREATE INDEX idx_mandates_umrn ON tanashvi_core.mandates(umrn);

-- 3.2 Lumpsum Transactions & Direct Orders (order_new)
CREATE TABLE IF NOT EXISTS tanashvi_core.orders (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    tenant_id UUID NOT NULL REFERENCES tanashvi_core.tenants(id) ON DELETE CASCADE,
    ucc_id UUID NOT NULL REFERENCES tanashvi_core.ucc_investors(id) ON DELETE RESTRICT,
    bank_account_id UUID REFERENCES tanashvi_core.ucc_bank_accounts(id),
    mandate_id UUID REFERENCES tanashvi_core.mandates(id),
    
    -- Core Identifiers: Internal Order ID mapped to BSE Order ID
    mem_ord_ref_id VARCHAR(32) NOT NULL UNIQUE,   -- Tanashvi Order ID (e.g. 'ORD-20261031-987654')
    bse_order_no VARCHAR(32),                     -- BSE Order Number (e.g. '20261031123456')
    bse_internal_ref_no VARCHAR(64),
    
    -- Transaction Classification
    order_type VARCHAR(20) NOT NULL CHECK (order_type IN ('PURCHASE', 'REDEMPTION', 'SWITCH')),
    purchase_type VARCHAR(20) CHECK (purchase_type IN ('FRESH', 'ADDITIONAL')),
    order_source VARCHAR(20) NOT NULL DEFAULT 'LUMPSUM' CHECK (order_source IN ('LUMPSUM', 'SIP_INSTALLMENT', 'STP_LEG', 'SWP_LEG')),
    
    -- Scheme Details
    scheme_bse_code VARCHAR(32) NOT NULL REFERENCES tanashvi_core.master_schemes(scheme_bse_code),
    dest_scheme_bse_code VARCHAR(32) REFERENCES tanashvi_core.master_schemes(scheme_bse_code), -- Switch target
    folio_number VARCHAR(64),                     -- Blank for fresh, required for additional/redemption/switch
    dest_folio_number VARCHAR(64),
    phys_or_demat VARCHAR(1) NOT NULL DEFAULT 'P' CHECK (phys_or_demat IN ('P', 'D')),
    
    -- Value Details
    amount NUMERIC(14, 2) NOT NULL,
    units NUMERIC(14, 4),
    is_units BOOLEAN NOT NULL DEFAULT FALSE,      -- True if redemption/switch specifies units instead of amount
    all_units BOOLEAN NOT NULL DEFAULT FALSE,     -- True if 'Redeem All Units' opted
    currency VARCHAR(3) NOT NULL DEFAULT 'INR',
    
    -- Regulatory Attribution (AMFI & SEBI Mandatory)
    sub_br_arn VARCHAR(32) NOT NULL,              -- Tenant MFD ARN (e.g., 'ARN-347849' or Tenant ARN)
    sub_br_code VARCHAR(32),                      -- Tenant Branch code
    euin VARCHAR(16),                             -- RM's EUIN
    euin_flag BOOLEAN NOT NULL DEFAULT TRUE,      -- TRUE if advisory EUIN declared, FALSE if execution-only
    partner_id VARCHAR(32),
    
    -- Payment & Gateway Tracking
    payment_mode VARCHAR(20) NOT NULL CHECK (payment_mode IN ('UPI', 'NETBANKING', 'NEFT_RTGS', 'MANDATE')),
    payment_status VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK (payment_status IN (
        'PENDING', 'LINK_GENERATED', 'SUCCESS', 'FAILED', 'REVERSED', 'EXPIRED'
    )),
    bse_payment_link TEXT,
    payment_ref_id VARCHAR(64),
    payment_confirmed_at TIMESTAMPTZ,
    
    -- Order State Machine Lifecycle
    status VARCHAR(30) NOT NULL DEFAULT 'DRAFT' CHECK (status IN (
        'DRAFT',
        'VALIDATED',
        'QUEUED_FOR_BSE',
        'SUBMITTED_TO_BSE',
        'ACCEPTED_BY_BSE',
        'REJECTED_BY_BSE',
        'AWAITING_PAYMENT',
        'PAYMENT_CONFIRMED',
        'PROCESSED_BY_RTA',
        'UNITS_ALLOTTED',
        'CANCELLED',
        'EXPIRED'
    )),
    rejection_code VARCHAR(32),
    rejection_reason TEXT,
    
    -- Cut-Off & NAV Allotment Tracking
    order_timestamp TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    cut_off_time TIME NOT NULL,
    is_same_day_nav BOOLEAN NOT NULL DEFAULT TRUE,
    allotted_nav NUMERIC(12, 4),
    allotted_units NUMERIC(14, 4),
    allotment_date DATE,
    
    -- Audit & Trace
    trace_id UUID NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_orders_tenant ON tanashvi_core.orders(tenant_id);
CREATE INDEX idx_orders_ucc ON tanashvi_core.orders(ucc_id);
CREATE INDEX idx_orders_mem_ref ON tanashvi_core.orders(mem_ord_ref_id);
CREATE INDEX idx_orders_bse_no ON tanashvi_core.orders(bse_order_no);
CREATE INDEX idx_orders_status ON tanashvi_core.orders(status);
CREATE INDEX idx_orders_created ON tanashvi_core.orders(created_at DESC);

-- 3.3 Systematic Transactions Engine: SIP, XSIP, STP, SWP (sxp_register)
CREATE TABLE IF NOT EXISTS tanashvi_core.systematic_registrations (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    tenant_id UUID NOT NULL REFERENCES tanashvi_core.tenants(id) ON DELETE CASCADE,
    ucc_id UUID NOT NULL REFERENCES tanashvi_core.ucc_investors(id) ON DELETE RESTRICT,
    mandate_id UUID REFERENCES tanashvi_core.mandates(id) ON DELETE RESTRICT,
    bank_account_id UUID REFERENCES tanashvi_core.ucc_bank_accounts(id),
    
    -- Identifiers: Internal Ref mapped to BSE Registration No
    mem_sxp_ref_id VARCHAR(32) NOT NULL UNIQUE,   -- Tanashvi Ref (e.g. 'SIP-20261031-112233')
    bse_reg_no VARCHAR(32),                       -- BSE StAR MF Registration Number
    
    -- Systematic Type
    sxp_type VARCHAR(10) NOT NULL CHECK (sxp_type IN ('SIP', 'XSIP', 'STP', 'SWP')),
    
    -- Scheme Details
    src_scheme_bse_code VARCHAR(32) NOT NULL REFERENCES tanashvi_core.master_schemes(scheme_bse_code),
    dest_scheme_bse_code VARCHAR(32) REFERENCES tanashvi_core.master_schemes(scheme_bse_code), -- Required for STP
    src_folio VARCHAR(64),
    dest_folio VARCHAR(64),
    phys_or_demat VARCHAR(1) NOT NULL DEFAULT 'P' CHECK (phys_or_demat IN ('P', 'D')),
    
    -- Schedule & Frequency
    frequency VARCHAR(5) NOT NULL CHECK (frequency IN ('d', 'w', 'm', 'q')), -- Daily, Weekly, Monthly, Quarterly
    installment_amount NUMERIC(14, 2) NOT NULL,
    units NUMERIC(14, 4),                         -- For STP/SWP based on units
    is_units BOOLEAN NOT NULL DEFAULT FALSE,
    installment_day INT NOT NULL CHECK (installment_day BETWEEN 1 AND 31),
    start_date DATE NOT NULL,
    end_date DATE,                                -- Null if perpetual
    is_perpetual BOOLEAN NOT NULL DEFAULT FALSE,
    total_installments INT,
    first_order_today BOOLEAN NOT NULL DEFAULT FALSE,
    
    -- Step-Up / Top-Up Configuration
    has_topup BOOLEAN NOT NULL DEFAULT FALSE,
    topup_type VARCHAR(10) CHECK (topup_type IN ('PERCENT', 'AMOUNT')),
    topup_value NUMERIC(14, 2),
    topup_frequency VARCHAR(10) CHECK (topup_frequency IN ('HALF_YEARLY', 'YEARLY')),
    
    -- Regulatory Attribution
    sub_br_arn VARCHAR(32) NOT NULL,
    sub_br_code VARCHAR(32),
    euin VARCHAR(16),
    euin_flag BOOLEAN NOT NULL DEFAULT TRUE,
    partner_id VARCHAR(32),
    
    -- Status Lifecycle
    status VARCHAR(20) NOT NULL DEFAULT 'INITIATED' CHECK (status IN (
        'INITIATED', 'SUBMITTED_TO_BSE', 'ACTIVE', 'PAUSED', 'RESUMED', 'CANCELLED', 'COMPLETED', 'REJECTED'
    )),
    pause_start_date DATE,
    pause_end_date DATE,
    cancellation_date DATE,
    rejection_reason TEXT,
    
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

