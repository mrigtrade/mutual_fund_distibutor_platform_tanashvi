    is_pan_exempt BOOLEAN NOT NULL DEFAULT FALSE,
    pan_exempt_category VARCHAR(10),
    ckyc_number VARCHAR(20),
    kyc_type VARCHAR(10) NOT NULL DEFAULT 'C' CHECK (kyc_type IN ('C', 'K')), -- CKYC / KRA
    kyc_verified BOOLEAN NOT NULL DEFAULT FALSE,
    
    -- Personal Information
    first_name VARCHAR(100) NOT NULL,
    middle_name VARCHAR(100),
    last_name VARCHAR(100) NOT NULL,
    dob DATE NOT NULL,
    gender VARCHAR(1) NOT NULL CHECK (gender IN ('M', 'F', 'O')),
    occupation_code VARCHAR(10) NOT NULL DEFAULT '01', -- '01' Business, '02' Services, '03' Professional, etc.
    
    -- Family & Relation Info
    father_name VARCHAR(150),
    spouse_name VARCHAR(150),
    
    -- Contact Information
    contact_number VARCHAR(20) NOT NULL,
    country_code VARCHAR(10) NOT NULL DEFAULT '91',
    whose_contact_number VARCHAR(10) NOT NULL DEFAULT 'SE', -- 'SE' Self, 'SP' Spouse, 'DC' Dependent Child, 'DP' Dependent Parent
    email_address VARCHAR(255) NOT NULL,
    whose_email_address VARCHAR(10) NOT NULL DEFAULT 'SE',
    contact_type VARCHAR(10) NOT NULL DEFAULT 'PR',          -- Primary
    
