-- 3.4 Systematic Installment Execution Ledger (Links every scheduled run to an actual order)
CREATE TABLE IF NOT EXISTS tanashvi_core.systematic_installments (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    sxp_id UUID NOT NULL REFERENCES tanashvi_core.systematic_registrations(id) ON DELETE CASCADE,
    tenant_id UUID NOT NULL REFERENCES tanashvi_core.tenants(id) ON DELETE CASCADE,
    order_id UUID REFERENCES tanashvi_core.orders(id) ON DELETE SET NULL,
    
    installment_sequence INT NOT NULL,
    scheduled_date DATE NOT NULL,
    execution_date DATE,
    amount NUMERIC(14, 2) NOT NULL,
    
    status VARCHAR(20) NOT NULL DEFAULT 'SCHEDULED' CHECK (status IN (
        'SCHEDULED', 'TRIGGERED', 'ORDER_CREATED', 'PAYMENT_PENDING', 'SUCCESS', 'FAILED', 'SKIPPED_PAUSED'
    )),
    failure_reason TEXT,
    
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    
    CONSTRAINT uq_sxp_installment_seq UNIQUE (sxp_id, installment_sequence)
);

CREATE INDEX idx_installments_sxp ON tanashvi_core.systematic_installments(sxp_id);
CREATE INDEX idx_installments_date ON tanashvi_core.systematic_installments(scheduled_date, status);

