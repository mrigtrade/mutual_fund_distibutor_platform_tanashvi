-- 2.1 Mutual Fund Scheme Master (BSE StAR MF v2 Canonical Catalog)
CREATE TABLE IF NOT EXISTS tanashvi_core.master_schemes (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    
    -- BSE Primary Keys
    scheme_bse_code VARCHAR(32) NOT NULL UNIQUE,     -- Canonical Unique BSE Scheme Code (e.g., '02-DP', 'PRTFGP-GR')
    scheme_isin VARCHAR(12) NOT NULL,                -- ISIN (e.g., 'INF209K01090')
    scheme_amfi_code VARCHAR(32),                    -- AMFI Code (e.g., '100033')
    scheme_cpc_code VARCHAR(32),                     -- Channel Partner Code
    
    -- Scheme Branding & Hierarchy
    name VARCHAR(255) NOT NULL,                      -- Full Scheme Name
    parent_scheme_code VARCHAR(64),
    parent_scheme_name VARCHAR(255),
    
    -- AMC & RTA Mapping
    scheme_amc_code VARCHAR(32) NOT NULL,            -- BSE AMC Identifier (e.g. 'NH32')
    scheme_amc_name VARCHAR(255) NOT NULL,           -- AMC Name (e.g., 'HDFC Asset Management Company')
    scheme_rta_code VARCHAR(32) NOT NULL,            -- RTA Code (e.g., 'CAMS', 'KARVY/KFIN')
    scheme_rta_name VARCHAR(100) NOT NULL,
    
    -- Classification
    scheme_plan VARCHAR(20) NOT NULL CHECK (scheme_plan IN ('Direct', 'Regular')),
    scheme_option VARCHAR(30) NOT NULL CHECK (scheme_option IN ('Growth', 'IDCW Payout', 'IDCW Reinvestment')),
    scheme_option_frequency VARCHAR(30),             -- 'DAILY', 'WEEKLY', 'MONTHLY', 'QUARTERLY', 'ANNUALLY'
    scheme_category VARCHAR(100),                    -- 'Equity', 'Debt', 'Hybrid', 'Solution Oriented', 'Other'
    scheme_sub_category VARCHAR(100),                -- 'Large Cap Fund', 'ELSS', 'Liquid Fund', 'Overnight Fund'
    scheme_investment_mode VARCHAR(20) DEFAULT 'ACTIVE', -- 'ACTIVE' or 'PASSIVE'
    scheme_face_value INT DEFAULT 10,
    
    -- Operational Lifecycle
    scheme_offer_status VARCHAR(20) NOT NULL DEFAULT 'OPEN' CHECK (scheme_offer_status IN ('NFO', 'OPEN', 'CLOSED')),
    scheme_offer_type VARCHAR(20) NOT NULL DEFAULT 'OPEN_ENDED' CHECK (scheme_offer_type IN ('OPEN_ENDED', 'CLOSED_ENDED', 'INTERVAL', 'NFO')),
    scheme_redemption_settlement_days VARCHAR(10) NOT NULL DEFAULT 'T1', -- 'T1', 'T2', 'T3', etc.
    
    -- Mode of Transaction Allowed
    is_physical_allowed BOOLEAN NOT NULL DEFAULT TRUE,
    is_demat_allowed BOOLEAN NOT NULL DEFAULT TRUE,
    
    -- Feature Availability Flags
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    sip_flag BOOLEAN NOT NULL DEFAULT FALSE,
    stp_in_flag BOOLEAN NOT NULL DEFAULT FALSE,
    stp_out_flag BOOLEAN NOT NULL DEFAULT FALSE,
    swp_flag BOOLEAN NOT NULL DEFAULT FALSE,
    switch_in_flag BOOLEAN NOT NULL DEFAULT FALSE,
    switch_out_flag BOOLEAN NOT NULL DEFAULT FALSE,
    
    -- Cut-Off Timings (Critical for Same-Day NAV Determination)
    -- Equity/Debt: 15:00 IST | Liquid/Overnight: 13:30 IST
    cutoff_time TIME NOT NULL DEFAULT '15:00:00',
    nav_settlement_type VARCHAR(20) NOT NULL DEFAULT 'HISTORIC_OR_CLOSING',
    
    -- Purchase & Redemption Constraints
    min_purchase_amount NUMERIC(14, 2) NOT NULL DEFAULT 500.00,
    min_additional_amount NUMERIC(14, 2) NOT NULL DEFAULT 500.00,
    purchase_amount_multiplier NUMERIC(14, 2) NOT NULL DEFAULT 1.00,
    max_purchase_amount NUMERIC(14, 2),
    min_redemption_amount NUMERIC(14, 2) DEFAULT 500.00,
    min_redemption_units NUMERIC(14, 4) DEFAULT 1.0000,
    
    -- Systematic (SIP/STP/SWP) Constraints
    min_sip_amount NUMERIC(14, 2) DEFAULT 500.00,
    sip_allowed_frequencies TEXT[] DEFAULT ARRAY['m'],  -- 'd', 'w', 'm', 'q'
    sip_allowed_dates INT[] DEFAULT ARRAY[1, 5, 10, 15, 20, 25],
    min_installments INT DEFAULT 6,
    max_installments INT DEFAULT 1200,
    
    -- Lockin period (e.g. 36 months for ELSS)
    lockin_period_value INT DEFAULT 0,
    lockin_period_unit VARCHAR(10) DEFAULT 'Months',
    
    -- Raw Synchronized Snapshot
    raw_bse_scheme_data JSONB,
    last_synced_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_schemes_isin ON tanashvi_core.master_schemes(scheme_isin);
CREATE INDEX idx_schemes_amc ON tanashvi_core.master_schemes(scheme_amc_code);
CREATE INDEX idx_schemes_category ON tanashvi_core.master_schemes(scheme_category, scheme_sub_category);
CREATE INDEX idx_schemes_active ON tanashvi_core.master_schemes(is_active, scheme_offer_status);

