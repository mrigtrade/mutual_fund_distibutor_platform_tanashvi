-- 1.1 Unique Client Code (UCC) Master
CREATE TABLE IF NOT EXISTS tanashvi_core.ucc_investors (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    tenant_id UUID NOT NULL REFERENCES tanashvi_core.tenants(id) ON DELETE CASCADE,
    
    -- BSE Client Code (e.g. 'UCC123456' unique per member/tenant)
    client_code VARCHAR(32) NOT NULL,
    
    -- Investor Classification
    holding_nature VARCHAR(10) NOT NULL CHECK (holding_nature IN ('SI', 'JO', 'AS')), -- Single, Joint, Anyone or Survivor
    tax_code VARCHAR(10) NOT NULL,                                                     -- '01' Individual, '02' HUF, etc.
    tax_status_desc VARCHAR(100) NOT NULL DEFAULT 'Individual',
    rdmp_idcw_pay_mode VARCHAR(10) NOT NULL DEFAULT '02',                              -- '01' Cheque, '02' Direct Credit, '03' NEFT/RTGS
    
    -- Client Mode: Strict Physical vs Demat Separation
    is_client_physical BOOLEAN NOT NULL DEFAULT TRUE,
    is_client_demat BOOLEAN NOT NULL DEFAULT FALSE,
    
    -- Demat Depository Details (Populated when is_client_demat is TRUE)
    depository_type VARCHAR(10) CHECK (depository_type IN ('CDSL', 'NSDL')),
    dp_id VARCHAR(32),        -- 8-character DP ID (e.g., IN300000 for NSDL)
    demat_client_id VARCHAR(32), -- 8-digit Client Beneficiary ID
    
    -- Nomination & Communication Preferences
    is_nomination_opted BOOLEAN NOT NULL DEFAULT TRUE,
    nomination_auth_mode VARCHAR(10) NOT NULL DEFAULT 'O' CHECK (nomination_auth_mode IN ('O', 'P')), -- Online / Physical
    comm_mode VARCHAR(10) NOT NULL DEFAULT 'E' CHECK (comm_mode IN ('E', 'P')),                       -- Electronic / Physical
    onboarding_channel VARCHAR(10) NOT NULL DEFAULT 'Z',                                              -- 'Z' API / Digital
    
    -- Regulatory MFD Routing Assigned at UCC Registration
    default_sub_broker_code VARCHAR(32),
    default_sub_broker_arn VARCHAR(32),
    default_euin VARCHAR(16),
    
    -- BSE StAR MF v2 Registration Lifecycle
    bse_status VARCHAR(20) NOT NULL DEFAULT 'DRAFT' CHECK (bse_status IN (
        'DRAFT', 'PENDING_SUBMISSION', 'SUBMITTED_TO_BSE', 'ACTIVE_APPROVED', 'REJECTED_BY_BSE', 'DEACTIVATED'
    )),
    bse_aof_ref_no VARCHAR(64),          -- AOF reference number generated by BSE
    bse_registration_date TIMESTAMPTZ,
    bse_last_sync_date TIMESTAMPTZ,
    bse_response_payload JSONB,
    
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    
    CONSTRAINT uq_tenant_client_code UNIQUE (tenant_id, client_code),
    CONSTRAINT chk_physical_or_demat CHECK (is_client_physical = TRUE OR is_client_demat = TRUE)
);

CREATE INDEX idx_ucc_tenant ON tanashvi_core.ucc_investors(tenant_id);
CREATE INDEX idx_ucc_client_code ON tanashvi_core.ucc_investors(client_code);
CREATE INDEX idx_ucc_bse_status ON tanashvi_core.ucc_investors(bse_status);

